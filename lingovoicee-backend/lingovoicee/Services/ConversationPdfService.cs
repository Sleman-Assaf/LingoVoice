using lingovoicee.Models.Entity;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;

namespace lingovoicee.Services
{
    public class ConversationPdfService
    {
        public byte[] GenerateConversationPdf(ConversationSession session)
        {
            QuestPDF.Settings.License = LicenseType.Community;

            return Document.Create(container =>
            {
                container.Page(page =>
                {
                    page.Size(PageSizes.A4);
                    page.Margin(35);

                    page.Header()
                        .Column(column =>
                        {
                            column.Item().Text("LingoVoice Conversation Report")
                                .FontSize(22)
                                .Bold();

                            column.Item().Text($"Session ID: {session.Id}")
                                .FontSize(10);

                            column.Item().Text($"Date: {session.StartedAt:yyyy-MM-dd HH:mm}")
                                .FontSize(10);

                            if (session.EndedAt != null)
                            {
                                column.Item().Text($"Ended At: {session.EndedAt:yyyy-MM-dd HH:mm}")
                                    .FontSize(10);
                            }

                            if (!string.IsNullOrWhiteSpace(session.TargetLanguage))
                            {
                                column.Item().Text($"Target Language: {session.TargetLanguage}")
                                    .FontSize(10);
                            }
                        });

                    page.Content()
                        .PaddingVertical(20)
                        .Column(column =>
                        {
                            column.Spacing(10);

                            if (session.Messages == null || !session.Messages.Any())
                            {
                                column.Item().Text("No conversation messages were saved for this session.")
                                    .FontSize(12);
                            }
                            else
                            {
                                foreach (var message in session.Messages.OrderBy(m => m.CreatedAt))
                                {
                                    column.Item()
                                        .Border(1)
                                        .BorderColor(Colors.Grey.Lighten2)
                                        .Padding(10)
                                        .Column(msg =>
                                        {
                                            msg.Item().Text(message.Sender)
                                                .Bold()
                                                .FontSize(12);

                                            msg.Item().Text(message.Text)
                                                .FontSize(11);

                                            msg.Item().Text(message.CreatedAt.ToString("HH:mm:ss"))
                                                .FontSize(8)
                                                .FontColor(Colors.Grey.Darken1);
                                        });
                                }
                            }
                        });

                    page.Footer()
                        .AlignCenter()
                        .Text(text =>
                        {
                            text.Span("Generated by LingoVoice - Page ");
                            text.CurrentPageNumber();
                            text.Span(" of ");
                            text.TotalPages();
                        });
                });
            }).GeneratePdf();
        }
    }
}